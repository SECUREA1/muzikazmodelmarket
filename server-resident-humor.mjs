export function humorMap(info={}){
 const text=[info.context?.worldName,info.context?.worldId,info.placeName].filter(Boolean).join(' ').toLowerCase();
 if(info.funhouseClown||/funhouse|clown/.test(text))return 'funhouse';
 if(/quarry|stockyard/.test(text))return 'quarry';
 if(/forestry|lumber/.test(text))return 'forestry';
 if(/tropical|island/.test(text))return 'island';
 if(/prison/.test(text))return 'prison';
 return info.context?.kind||'community';
}
