test('persistent account sessions survive time and restart but explicit logout revokes them', async t => {
  const dir = await mkdtemp(join(tmpdir(),'persistent-login-')); t.after(()=>rm(dir,{recursive:true,force:true}));
  let now = Date.now(); const file = join(dir,'sessions.json');
  const options = { persistent:true, ttlSeconds:60, clock:()=>now, maxActivePerAccount:1 };
  const store = new DurableSessionStore(file,options), account = {accountId:'member-a'};
  const first = await store.createSession(account); await store.createSession(account);
  now += 800 * 86400000;
  const restarted = new DurableSessionStore(file,options);
  assert.equal((await restarted.authenticateSession(first.token)).expiresAt,null);
  await restarted.revokeSession(first.token); assert.equal(await store.authenticateSession(first.token),null);
  const game = new DurableSessionStore(join(dir,'game.json'),{...options,kind:'game'}), transient = await game.createSession(account);
  now += 61000; assert.equal(await game.authenticateSession(transient.token),null);
});
test('identical land entitlements reveal into separate durable plots, with no reissue after resale', async t => {
  const dir=await mkdtemp(join(tmpdir(),'reveal-land-')); t.after(()=>rm(dir,{recursive:true,force:true}));
  const file=join(dir,'users.json'),db=new UserJsonDatabase(file);
  const account=id=>({accountId:id,mzkBalance:200,gameAssets:[],landAssets:['Unrevealed Land'],bottleClaims:[]});
  const a=await db.ensureAccount(account('member-a')),b=await db.ensureAccount(account('member-b'));
  const aid=a.items[0].id,bid=b.items[0].id;
  await assert.rejects(db.revealLand('account:outsider',aid),/not in your Backpack/);
  const [one,two]=await Promise.all([db.revealLand(a.walletId,aid),db.revealLand(b.walletId,bid)]);
  assert.notEqual(one.spaceId,two.spaceId); assert.equal((await db.revealLand(a.walletId,aid)).spaceId,one.spaceId);
  await db.ensureAccount(account('member-a'));
  assert.equal((await db.get(a.walletId)).items.length,1);assert.equal((await db.get(a.walletId)).items[0].type,'land-deed');
  await db.listItem(a.walletId,one.id,50);await db.trade({buyerId:b.walletId,sellerId:a.walletId,itemId:one.id,requestId:'land-resale',expectedPriceMzk:50});
  await db.ensureAccount(account('member-a'));
  assert.equal((await db.get(a.walletId)).items.length,0);
  const restarted=new UserJsonDatabase(file),plots=await restarted.memberPlots();
  assert.equal(plots.find(deed=>deed.id===one.id).ownerId,b.walletId);
  assert.equal((await restarted.revealLand(b.walletId,one.id)).playUrl,one.playUrl);
  await assert.rejects(restarted.revealLand(a.walletId,one.id),/not in your Backpack/);
});
